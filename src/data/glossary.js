// Cette fonction renvoie un sous-ensemble aléatoire de termes
export function getRandomTerms(count = 3) {
  const shuffled = [...glossaryTerms].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

// Cette fonction renvoie les termes par catégorie
export function getTermsByCategory() {
  return glossaryTerms.reduce((acc, term) => {
    if (!acc[term.category]) {
      acc[term.category] = [];
    }
    acc[term.category].push(term);
    return acc;
  }, {});
}
